const express = require('express');
const cors = require('cors');

const app = express();

app.use(cors());
app.use(express.json());
app.use(express.urlencoded({ extended: true }));

app.get('/', (req, res) => {
  res.status(200).json({
    success: true,
    message: 'AI-Powered Health Risk Prediction and Monitoring System Backend API is active',
  });
});

module.exports = app;
